#!/usr/bin/env python3
"""
Builds copy-paste deploy files for the Supabase dashboard (no CLI or network access needed):
  supabase/deploy/01_estructura.sql            all migrations, in order (SQL Editor)
  supabase/deploy/functions/<name>.ts          each Edge Function as ONE file (dashboard editor)
  supabase/deploy/cron.sql                     scheduled email worker for this project
  <data_out>/02_datos_iniciales.sql            initial migration data (contains personal data: never commit)
Usage: python3 -I scripts/build_deploy.py <project_ref> <migration_out_dir> <data_out_dir>
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ref, mig_out, data_out = sys.argv[1], sys.argv[2], sys.argv[3]
dep = os.path.join(ROOT, 'supabase', 'deploy')
os.makedirs(os.path.join(dep, 'functions'), exist_ok=True)
os.makedirs(data_out, exist_ok=True)

# 1) schema
parts = ['-- CESANTONI Samples · estructura completa. Pegar TODO en Supabase › SQL Editor › Run (una sola vez).\n']
for f in sorted(glob.glob(os.path.join(ROOT, 'supabase', 'migrations', '*.sql'))):
    parts.append(f'\n-- ===================================================== {os.path.basename(f)}\n')
    parts.append(open(f).read())
open(os.path.join(dep, '01_estructura.sql'), 'w').write(''.join(parts))

# 2) single-file functions: inline ../_shared/*.ts
def shared(name):
    src = open(os.path.join(ROOT, 'supabase', 'functions', '_shared', name)).read()
    return re.sub(r'^export ', '', src, flags=re.M)

for fn in ('submit-request', 'notify-worker', 'email-webhook'):
    src = open(os.path.join(ROOT, 'supabase', 'functions', fn, 'index.ts')).read()
    inlined = []
    for m in re.finditer(r"^import \{[^}]*\} from '\.\./_shared/([a-z]+\.ts)';\n", src, flags=re.M):
        inlined.append(f'// ---- inlined from _shared/{m.group(1)}\n' + shared(m.group(1)))
    body = re.sub(r"^import \{[^}]*\} from '\.\./_shared/[a-z]+\.ts';\n", '', src, flags=re.M)
    open(os.path.join(dep, 'functions', f'{fn}.ts'), 'w').write(
        f'// {fn} — single-file version for the Supabase dashboard editor (generated by scripts/build_deploy.py)\n'
        + '\n'.join(inlined) + '\n// ---- function\n' + body)

# 3) cron for this project
cron = open(os.path.join(dep, 'cron.sql')).read().replace('<PROJECT_REF>', ref)
open(os.path.join(dep, 'cron_proyecto.sql'), 'w').write(cron)

# 4) data for the SQL editor: same transaction, without switching role (the editor runs as postgres)
data = open(os.path.join(mig_out, 'load.sql')).read()
data = data.replace('set local role service_role;\n', '').replace('reset role;\n', '')
open(os.path.join(data_out, '02_datos_iniciales.sql'), 'w').write(
    '-- CESANTONI Samples · datos iniciales (inventario Houston + folios antiguos). CONTIENE DATOS PERSONALES: no subir a GitHub.\n'
    '-- Pegar en Supabase › SQL Editor › Run, DESPUÉS de 01_estructura.sql. Se aplica en una sola transacción.\n' + data)
print('ok')
